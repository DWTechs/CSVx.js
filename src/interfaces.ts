/**
 * Configuration options for CSV export and conversion.
 */
export interface Options {
  /** MIME type for the CSV payload (default: `'text/csv'`). */
  data: string;
  /** Character encoding (default: `'utf-8'`). */
  charset: string;
  /** Whether the first row contains column header labels (default: `true`). */
  labels: boolean;
  /** Character used to wrap field values (default: `'"'`). */
  quote: string;
  /** Field delimiter character(s) (default: `','`). */
  separator: string;
  /** Row line-ending sequence (default: `'\r\n'`). */
  CRLF: string;
  /** Custom mapping of object property keys to header column labels (default: `null`). */
  customLabels: Record<string, string> | null;
  /** Whether to prompt the user with the native file-save dialog when supported (default: `false`). */
  save: boolean;
  /** Whether to prepend a UTF-8 Byte Order Mark (`\uFEFF`) for Excel compatibility (default: `false`). */
  bom: boolean;
  [key: string]: string[] | string | boolean | Record<string, string> | null;
}

/**
 * CSS class names applied to HTML elements generated by `Convert.table()`.
 */
export interface CSS {
  /** CSS class(es) applied to the `<table>` element (default: `''`). */
  table: string;
  /** CSS class(es) applied to `<th>` header cells (default: `''`). */
  th: string;
  [key: string]: string;
}
